                "    def __init__(self, gamma_neg=4.0, gamma_pos=1.0, clip=0.05, eps=1e-8, class_weights=None):\n",
                "        super().__init__()\n",
                "        self.gamma_neg = gamma_neg\n",
                "        self.gamma_pos = gamma_pos\n",
                "        self.clip = clip\n",
                "        self.eps = eps\n",
                "        self.class_weights = class_weights\n",
